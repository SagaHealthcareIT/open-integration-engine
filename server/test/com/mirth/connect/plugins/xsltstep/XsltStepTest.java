package com.mirth.connect.plugins.xsltstep;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.util.LinkedList;

import javax.xml.XMLConstants;
import javax.xml.transform.TransformerFactory;

import org.apache.commons.io.FileUtils;
import org.apache.commons.text.StringEscapeUtils;
import org.junit.BeforeClass;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

import com.mirth.connect.donkey.model.message.ConnectorMessage;
import com.mirth.connect.model.IteratorProperties;
import com.mirth.connect.model.Step;
import com.mirth.connect.util.JavaScriptTestUtil;

/**
 * Regression tests for CVE-2026-78224: the script generated by the XSLT step created a
 * TransformerFactory with default settings, so a DOCTYPE in the (attacker-controlled) source XML
 * could read server-local files through external entities or stall the channel on a slow entity.
 */
public class XsltStepTest {

    private static final String CANARY = "XSLT_XXE_CANARY_7f3a9c";
    private static final String RESULT_VARIABLE = "xsltResult";

    // @formatter:off
    private static final String IDENTITY_TEMPLATE =
        "<xsl:stylesheet version=\"1.0\" xmlns:xsl=\"http://www.w3.org/1999/XSL/Transform\">" +
        "    <xsl:output method=\"xml\" omit-xml-declaration=\"yes\"/>" +
        "    <xsl:template match=\"/\">" +
        "        <xsl:copy-of select=\".\"/>" +
        "    </xsl:template>" +
        "</xsl:stylesheet>";
    // @formatter:on

    @Rule
    public TemporaryFolder tempFolder = new TemporaryFolder();

    @BeforeClass
    public static void setup() throws Exception {
        JavaScriptTestUtil.setup();
    }

    @Test
    public void testGeneratedScriptHardensTransformerFactory() throws Exception {
        XsltStep step = newStep("'<d/>'", IDENTITY_TEMPLATE);

        assertHardened(step.getScript(true));
        assertHardened(step.getIterationScript(true, new LinkedList<IteratorProperties<Step>>()));
    }

    @Test
    public void testGeneratedScriptHardensCustomTransformerFactory() throws Exception {
        XsltStep step = newStep("'<d/>'", IDENTITY_TEMPLATE);
        step.setUseCustomFactory(true);
        step.setCustomFactory("com.example.CustomTransformerFactory");

        String script = step.getScript(true);
        assertTrue(script.contains("TransformerFactory.newInstance(\"com.example.CustomTransformerFactory\", null)"));
        assertHardened(script);
    }

    @Test
    public void testBenignXmlStillTransforms() throws Exception {
        XsltStep step = newStep("'<d><v>1</v></d>'", IDENTITY_TEMPLATE);

        String result = transform(step);

        assertEquals("<d><v>1</v></d>", result);
    }

    @Test
    public void testExternalGeneralEntityIsNotResolved() throws Exception {
        File secret = writeCanaryFile("secret.txt");
        String sourceXml = "<?xml version=\"1.0\"?><!DOCTYPE d [<!ENTITY x SYSTEM \"" + secret.toURI() + "\">]><d>&x;</d>";
        XsltStep step = newStep(jsLiteral(sourceXml), IDENTITY_TEMPLATE);

        assertCanaryNotLeaked(step);
    }

    @Test
    public void testExternalDtdIsNotLoaded() throws Exception {
        File secret = writeCanaryFile("secret.txt");
        File dtd = new File(tempFolder.getRoot(), "leak.dtd");
        FileUtils.writeStringToFile(dtd, "<!ENTITY x SYSTEM \"" + secret.toURI() + "\">", StandardCharsets.UTF_8);
        String sourceXml = "<?xml version=\"1.0\"?><!DOCTYPE d SYSTEM \"" + dtd.toURI() + "\"><d>&x;</d>";
        XsltStep step = newStep(jsLiteral(sourceXml), IDENTITY_TEMPLATE);

        assertCanaryNotLeaked(step);
    }

    @Test
    public void testExternalEntityIsNotResolvedWithCustomFactory() throws Exception {
        File secret = writeCanaryFile("secret.txt");
        String sourceXml = "<?xml version=\"1.0\"?><!DOCTYPE d [<!ENTITY x SYSTEM \"" + secret.toURI() + "\">]><d>&x;</d>";
        XsltStep step = newStep(jsLiteral(sourceXml), IDENTITY_TEMPLATE);
        step.setUseCustomFactory(true);
        step.setCustomFactory("com.sun.org.apache.xalan.internal.xsltc.trax.TransformerFactoryImpl");

        assertCanaryNotLeaked(step);
    }

    /**
     * With the JDK factory the hardened transform must fail on the external reference itself
     * (XSLTC names the accessExternalDTD restriction), so an unrelated script error cannot pass
     * as "hardened".
     */
    private void assertCanaryNotLeaked(XsltStep step) throws Exception {
        String result = null;
        Exception failure = null;

        try {
            result = transform(step);
        } catch (Exception e) {
            failure = e;
        }

        assertNull("external entity was resolved: " + result, result);
        assertNotNull(failure);
        String message = String.valueOf(failure.getMessage());
        assertFalse("external entity was resolved: " + message, message.contains(CANARY));
        assertTrue("expected the accessExternalDTD restriction, got: " + message, message.contains("accessExternalDTD"));
    }

    private static class RejectingTransformerFactory extends TransformerFactory {
        @Override
        public void setAttribute(String name, Object value) {
            throw new IllegalArgumentException("Unrecognized configuration feature: " + name);
        }

        @Override
        public Object getAttribute(String name) {
            throw new IllegalArgumentException(name);
        }

        @Override
        public javax.xml.transform.Transformer newTransformer(javax.xml.transform.Source source) {
            throw new UnsupportedOperationException();
        }

        @Override
        public javax.xml.transform.Transformer newTransformer() {
            throw new UnsupportedOperationException();
        }

        @Override
        public javax.xml.transform.Templates newTemplates(javax.xml.transform.Source source) {
            throw new UnsupportedOperationException();
        }

        @Override
        public javax.xml.transform.Source getAssociatedStylesheet(javax.xml.transform.Source source, String media, String title, String charset) {
            throw new UnsupportedOperationException();
        }

        @Override
        public void setURIResolver(javax.xml.transform.URIResolver resolver) {}

        @Override
        public javax.xml.transform.URIResolver getURIResolver() {
            return null;
        }

        @Override
        public void setFeature(String name, boolean value) {}

        @Override
        public boolean getFeature(String name) {
            return false;
        }

        @Override
        public void setErrorListener(javax.xml.transform.ErrorListener listener) {}

        @Override
        public javax.xml.transform.ErrorListener getErrorListener() {
            return null;
        }
    }

    private static void assertHardened(String script) {
        String hardening = "Packages.com.mirth.connect.plugins.xsltstep.XsltStep.hardenTransformerFactory(tFactory);";
        assertTrue(script, script.contains(hardening));
        // Stylesheet access is channel-author content and is deliberately not restricted
        assertFalse(script, script.contains("ACCESS_EXTERNAL_STYLESHEET"));
        // The factory must be hardened before it is used
        assertTrue(script.indexOf(hardening) < script.indexOf("tFactory.newTransformer("));
    }

    @Test
    public void testHardenTransformerFactorySetsDtdRestriction() throws Exception {
        TransformerFactory factory = TransformerFactory.newInstance();

        XsltStep.hardenTransformerFactory(factory);

        assertEquals("", factory.getAttribute(XMLConstants.ACCESS_EXTERNAL_DTD));
    }

    /**
     * A factory that predates JAXP 1.5 (e.g. Saxon 9.x attached as a channel resource) must not
     * start failing every message after the upgrade; it is logged instead.
     */
    @Test
    public void testHardenTransformerFactoryToleratesFactoryWithoutDtdRestriction() throws Exception {
        TransformerFactory rejecting = new RejectingTransformerFactory();

        XsltStep.hardenTransformerFactory(rejecting);
        XsltStep.hardenTransformerFactory(rejecting);
    }

    @Test
    public void testBenignXmlStillTransformsWithCustomFactory() throws Exception {
        XsltStep step = newStep("'<d><v>1</v></d>'", IDENTITY_TEMPLATE);
        step.setUseCustomFactory(true);
        step.setCustomFactory("com.sun.org.apache.xalan.internal.xsltc.trax.TransformerFactoryImpl");

        assertEquals("<d><v>1</v></d>", transform(step));
    }

    /**
     * document() in the stylesheet is channel-author content and must keep working: the fix only
     * restricts entity resolution in the (message-supplied) source document. Relies on the JDK
     * default of ACCESS_EXTERNAL_STYLESHEET=all (no jaxp.properties override on the build host).
     */
    @Test
    public void testStylesheetDocumentFunctionStillWorks() throws Exception {
        File lookup = new File(tempFolder.getRoot(), "lookup.xml");
        FileUtils.writeStringToFile(lookup, "<lookup><v>LOOKED_UP</v></lookup>", StandardCharsets.UTF_8);
        // @formatter:off
        String template =
            "<xsl:stylesheet version=\"1.0\" xmlns:xsl=\"http://www.w3.org/1999/XSL/Transform\">" +
            "    <xsl:output method=\"text\"/>" +
            "    <xsl:template match=\"/\">" +
            "        <xsl:value-of select=\"document('" + lookup.toURI() + "')/lookup/v\"/>" +
            "    </xsl:template>" +
            "</xsl:stylesheet>";
        // @formatter:on
        XsltStep step = newStep("'<d/>'", template);

        assertEquals("LOOKED_UP", transform(step).trim());
    }

    private static XsltStep newStep(String sourceXml, String template) {
        XsltStep step = new XsltStep();
        step.setSourceXml(sourceXml);
        step.setResultVariable(RESULT_VARIABLE);
        step.setTemplate(template);
        return step;
    }

    private static String transform(XsltStep step) throws Exception {
        ConnectorMessage connectorMessage = new ConnectorMessage();
        JavaScriptTestUtil.testTransformerStep(step, connectorMessage);
        Object result = connectorMessage.getChannelMap().get(RESULT_VARIABLE);
        assertNotNull(result);
        return result.toString();
    }

    private File writeCanaryFile(String name) throws Exception {
        File file = new File(tempFolder.getRoot(), name);
        FileUtils.writeStringToFile(file, CANARY, StandardCharsets.UTF_8);
        return file;
    }

    private static String jsLiteral(String value) {
        return "'" + StringEscapeUtils.escapeEcmaScript(value) + "'";
    }
}
